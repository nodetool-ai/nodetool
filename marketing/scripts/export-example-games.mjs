import { execFile } from "node:child_process";
import { copyFile, cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const root = fileURLToPath(new URL("../../", import.meta.url));
const games = [
  { slug: "kindle", genre: "Platform adventure" },
  { slug: "lumen", genre: "Forest exploration" },
  { slug: "neon-drift", genre: "Arena shooter" }
];
const scratch = await mkdtemp(join(tmpdir(), "nodetool-marketing-games-"));
const entries = [];
try {
  for (const game of games) {
    const example = JSON.parse(await readFile(join(root, `packages/base-nodes/nodetool/examples/games/${game.slug}.game.json`), "utf8"));
    const assetsDir = join(scratch, game.slug);
    await mkdir(assetsDir);
    for (const binding of Object.values(example.document.assets)) {
      if (binding.assetId.startsWith("builtin:")) continue;
      const prefix = `package://nodetool-base/games/${game.slug}/`;
      if (!binding.assetId.startsWith(prefix)) throw new Error(`Unexpected source asset: ${binding.assetId}`);
      const filename = binding.assetId.slice(prefix.length);
      if (filename.includes("/") || filename.includes("\\")) throw new Error(`Unexpected asset filename: ${filename}`);
      const id = binding.digest.slice(0, 32);
      await copyFile(join(root, `packages/base-nodes/nodetool/assets/nodetool-base/games/${game.slug}/${filename}`), join(assetsDir, `${id}.${filename.split(".").pop()}`));
      binding.assetId = id;
    }
    const documentPath = join(scratch, `${game.slug}.json`);
    await writeFile(documentPath, JSON.stringify(example.document));
    const output = join(scratch, `${game.slug}-web`);
    const result = await run(process.execPath, [join(root, "packages/cli/dist/nodetool.js"), "game", "build", documentPath, "--assets-dir", assetsDir, "--out", output]);
    process.stdout.write(result.stdout);
    await copyFile(join(root, `packages/base-nodes/nodetool/assets/nodetool-base/games/${game.slug}/poster.jpg`), join(output, "poster.jpg"));
    const htmlPath = join(output, "index.html");
    const html = await readFile(htmlPath, "utf8");
    const title = example.name.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
    await writeFile(htmlPath, html.replace("<title>NodeTool Game</title>", `<meta name="robots" content="noindex"><title>${title} | NodeTool Game</title>`));
    const playerPath = join(output, "player-v1.js");
    const player = await readFile(playerPath, "utf8");
    await writeFile(playerPath, player.replace(/^[ \t]+$/gm, ""));
    entries.push({ ...game, name: example.name, description: example.description, controls: example.controls });
  }
  for (const game of games) {
    const output = join(root, `marketing/public/games/${game.slug}`);
    await rm(output, { recursive: true, force: true });
    await cp(join(scratch, `${game.slug}-web`), output, { recursive: true });
  }
  await writeFile(join(root, "marketing/src/data/gameExamples.generated.ts"), `// Generated by scripts/export-example-games.mjs. Do not edit.\nexport const gameExamples = ${JSON.stringify(entries, null, 2)} as const;\n`);
} finally {
  await rm(scratch, { recursive: true, force: true });
}
