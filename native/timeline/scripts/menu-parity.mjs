// Compares the menu bar with docs/premiere-menus.txt and writes docs/menu-parity.md.
// A report of gaps, not a gate: it never fails on a gap, as `cargo xtask parity` of
// FilmCraft does without --min (xtask/src/parity.rs, licenses/FilmCraft-MIT.txt).
//
//   node native/timeline/scripts/menu-parity.mjs <path to nodetool-timeline> [--check]
//
// --check fails when the checked-in report no longer matches, for a person to rerun.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const norm = (label) => label.replace(/…$/, "").trim().toLowerCase();

// Reference lines to {path: ["Menu", "Sub", "Item"], ours}. Comments and blanks are skipped.
export function parseReference(text) {
  const items = [];
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const [left, ours] = trimmed.split(" = ");
    const path = left.split(" > ").map((part) => part.trim());
    if (path.length < 2) throw new Error(`A reference item needs its menu: ${line}`);
    items.push({ path, ours: ours?.trim() ?? path.at(-1) });
  }
  return items;
}

// Our menus (--dump-menus) to a list of {path}, leaves only.
export function flattenMenus(menus) {
  const out = [];
  const visit = (items, path) => {
    for (const item of items ?? []) {
      if (item.items?.length) visit(item.items, [...path, item.label]);
      else out.push({ path: [...path, item.label], action: item.action });
    }
  };
  for (const menu of menus) visit(menu.items, [menu.label]);
  return out;
}

// Same place: our label at the reference's menu and submenus. Elsewhere: our label under
// another path. Missing: no such label. A label match is presence only, not behaviour.
export function compareMenus(reference, ours) {
  const key = (path) => path.map(norm).join(" > ");
  const places = new Set(ours.map((item) => key(item.path)));
  const byLabel = new Map();
  for (const item of ours) {
    const label = norm(item.path.at(-1));
    if (!byLabel.has(label)) byLabel.set(label, []);
    byLabel.get(label).push(item.path.join(" > "));
  }
  const samePlace = [];
  const elsewhere = [];
  const missing = [];
  const matched = new Set();
  for (const item of reference) {
    const name = item.path.join(" > ");
    const wanted = [...item.path.slice(0, -1), item.ours];
    if (places.has(key(wanted))) {
      samePlace.push({ name, ours: wanted.join(" > ") });
      matched.add(key(wanted));
    } else if (byLabel.has(norm(item.ours))) {
      elsewhere.push({ name, ours: byLabel.get(norm(item.ours)).join(", ") });
      for (const place of byLabel.get(norm(item.ours))) matched.add(key(place.split(" > ")));
    } else {
      missing.push({ name });
    }
  }
  const extra = ours.filter((item) => !matched.has(key(item.path))).map((item) => item.path.join(" > "));
  return { samePlace, elsewhere, missing, extra };
}

export function formatReport({ samePlace, elsewhere, missing, extra }) {
  const total = samePlace.length + elsewhere.length + missing.length;
  const lines = [
    "# Menu labels compared with Premiere",
    "",
    "Generated by `scripts/menu-parity.mjs` from `docs/premiere-menus.txt` and `nodetool-timeline --dump-menus`.",
    "This is a report, not a gate. A label match shows the label exists, not that it behaves the same.",
    "A missing item may be out of scope: the issue that adds a feature adds its menu item.",
    "",
    `${total} reference items: ${samePlace.length} in the same place, ${elsewhere.length} elsewhere, ${missing.length} missing. ${extra.length} of our items have no reference item.`,
    "",
    "## Elsewhere",
    "",
    ...elsewhere.map((item) => `- ${item.name}: ours is ${item.ours}`),
    "",
    "## Missing",
    "",
    ...missing.map((item) => `- ${item.name}`),
    "",
    "## Ours only",
    "",
    ...extra.map((item) => `- ${item}`),
    "",
    "## Same place",
    "",
    ...samePlace.map((item) => `- ${item.name}`),
    "",
  ];
  return lines.join("\n");
}

function main() {
  const [binary, flag] = process.argv.slice(2);
  if (!binary) {
    console.error("usage: menu-parity.mjs <path to nodetool-timeline> [--check]");
    return 2;
  }
  const dump = spawnSync(binary, ["--dump-menus"], { encoding: "utf8", env: { ...process.env, QT_QPA_PLATFORM: "offscreen" } });
  if (dump.status !== 0) {
    console.error(`${binary} --dump-menus failed: ${dump.stderr}`);
    return 1;
  }
  const docs = join(dirname(fileURLToPath(import.meta.url)), "..", "docs");
  const reference = parseReference(readFileSync(join(docs, "premiere-menus.txt"), "utf8"));
  const report = formatReport(compareMenus(reference, flattenMenus(JSON.parse(dump.stdout))));
  const target = join(docs, "menu-parity.md");
  if (flag === "--check") {
    if (readFileSync(target, "utf8") !== report) {
      console.error("docs/menu-parity.md is out of date. Rerun scripts/menu-parity.mjs.");
      return 1;
    }
    return 0;
  }
  writeFileSync(target, report);
  console.log(report.split("\n")[6]);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main());
