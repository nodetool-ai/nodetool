#!/usr/bin/env node
// Writes qml/Icons.qml: the SVG path data of the Material icons the web
// timeline uses, read from @mui/icons-material (MIT), so the QML draws the
// same glyphs with a Shape. Rerun after adding a name to ICONS.
//
//   node native/timeline/scripts/extract-icons.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

// QML property name -> MUI icon export.
const ICONS = {
  videocam: "VideocamOutlined",
  audiotrack: "AudiotrackOutlined",
  layers: "LayersOutlined",
  subtitles: "SubtitlesOutlined",
  piano: "PianoOutlined",
  queueMusic: "QueueMusicOutlined",
  visibility: "VisibilityOutlined",
  visibilityOff: "VisibilityOffOutlined",
  lock: "LockOutlined",
  lockOpen: "LockOpenOutlined",
  sync: "SyncOutlined",
  syncDisabled: "SyncDisabledOutlined",
  volumeOffOutlined: "VolumeOffOutlined",
  volumeUpOutlined: "VolumeUpOutlined",
  deleteOutline: "DeleteOutlineOutlined",
  graphicEq: "GraphicEqOutlined",
  showChart: "ShowChartOutlined",
  dragIndicator: "DragIndicator",
  add: "AddOutlined",
  remove: "Remove",
  fitScreen: "FitScreen",
  skipPrevious: "SkipPrevious",
  navigateBefore: "NavigateBefore",
  playArrow: "PlayArrow",
  pause: "Pause",
  stop: "Stop",
  repeat: "Repeat",
  navigateNext: "NavigateNext",
  skipNext: "SkipNext",
  volumeUp: "VolumeUp",
  fullscreen: "Fullscreen"
};

// The exports map hides package.json; an icon resolves to the package root.
const pkgDir = path.dirname(require.resolve("@mui/icons-material/PlayArrow"));
const lines = [];
let count = 0;
for (const [name, file] of Object.entries(ICONS)) {
  const source = readFileSync(path.join(pkgDir, "esm", `${file}.js`), "utf8");
  const elements = [...source.matchAll(/_jsx\("(\w+)"/g)].map((m) => m[1]);
  if (elements.some((e) => e !== "path")) {
    throw new Error(`${file}: only <path> elements are supported, found ${elements.join(", ")}`);
  }
  const paths = [...source.matchAll(/\bd: "([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`${file}: no path data`);
  lines.push(`    // ${file}`);
  lines.push(`    readonly property string ${name}: "${paths.join(" ")}"`);
  count += 1;
}

const out = `// Generated by scripts/extract-icons.mjs from @mui/icons-material. Do not edit.
pragma Singleton
import QtQuick

// SVG path data in the 24 x 24 Material icon box. Draw with Tracks/Icon.qml.
QtObject {
${lines.join("\n")}
}
`;
const target = path.join(here, "..", "qml", "Icons.qml");
writeFileSync(target, out);
console.log(`wrote ${count} icons to ${path.relative(process.cwd(), target)}`);
if (count !== Object.keys(ICONS).length) process.exit(1);
