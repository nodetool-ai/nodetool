import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { cases } from '../pixels/oracle.mjs';
import { measure } from '../../render2d/check-example-stills.mjs';

const binary = path.resolve(process.argv[2]);
const run = fs.mkdtempSync(path.join(process.env.TMPDIR ?? os.tmpdir(), 'motion-blur-export-'));
const document = structuredClone(cases().find((row) => row.name === 'nested-groups').document);
document.durationMs = 800;
const clip = document.clips.find((item) => item.id === 'child-a');
assert(clip?.parentId);
clip.motionBlur = { samplesPerFrame: 4, shutterAngle: 270 };
const file = path.join(run, 'document.json');
const original = JSON.stringify(document); fs.writeFileSync(file, original);
const stills = path.join(run, 'stills');
execFileSync(binary, [file, '--stills', stills, '--still-frames', '21', '--decode', 'sw'], { timeout: 180000, stdio: 'pipe' });
const still = path.join(stills, 'frame_000021.png');
assert(fs.existsSync(still));
const archive = path.join(run, 'frames.zip');
execFileSync(binary, [file, '--export', archive, '--format', 'png_sequence'], { timeout: 300000, stdio: 'pipe' });
const files = execFileSync('unzip', ['-Z1', archive], { encoding: 'utf8' }).trim().split('\n').filter((name) => name.endsWith('.png'));
assert.equal(files.length, 24);
const pngName = files.find((name) => /frame_000022\.png$/.test(name));
assert(pngName, 'PNG export must contain the 22nd frame');
const png = path.join(run, 'export.png');
fs.writeFileSync(png, execFileSync('unzip', ['-p', archive, pngName], { maxBuffer: 64 * 1024 * 1024 }));
assert.equal(measure(still, png), Infinity, 'preview and PNG export must agree');
const video = path.join(run, 'export.mp4');
execFileSync(binary, [file, '--export', video, '--format', 'mp4'], { timeout: 300000, stdio: 'pipe' });
const decoded = path.join(run, 'decoded.png');
execFileSync('ffmpeg', ['-v', 'error', '-i', video, '-vf', 'select=eq(n\\,21)', '-frames:v', '1', decoded], { timeout: 30000, stdio: 'pipe' });
assert(fs.existsSync(decoded));
assert(measure(still, decoded) >= 35, 'encoded frame must match preview within codec loss');
assert.equal(fs.readFileSync(file, 'utf8'), original);
console.log(JSON.stringify({ run, pngFrames: files.length, encodedPsnr: measure(still, decoded) }));
