#!/usr/bin/env node
// Compiles the kernel library to one standalone WebAssembly module and writes
// it, base64-encoded, into packages/kernels/src/generated/kernels-wasm.ts.
//
// The module is embedded in a source file, not shipped as a separate asset,
// so that every host that bundles the package (the server, the packaged
// Electron backend, the web app and the graph runner's guest bundle) has it
// without a file lookup that could fail at run time (risk R16 of the plan).
//
//   node native/kernels/scripts/build-wasm.mjs           # rebuild and write
//   node native/kernels/scripts/build-wasm.mjs --check   # fail on drift
//
// Needs Emscripten (`emcc`) on PATH. --check compares against the committed
// file only when the committed file records the same emcc version, because a
// different compiler version can emit different but equivalent bytes.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repo = resolve(root, "../..");
const output = join(repo, "packages/kernels/src/generated/kernels-wasm.ts");
const sources = ["audio.cpp", "biquad.cpp", "image.cpp", "pcm.cpp", "synth.cpp"].map((f) =>
  join(root, "src", f)
);
const check = process.argv.includes("--check");

/** Every `nt_*` function that kernels.h declares with NT_KERNEL_API. */
function exportedKernels() {
  const header = readFileSync(join(root, "include/nodetool/kernels.h"), "utf8");
  const names = [...header.matchAll(/NT_KERNEL_API\s+[\w\s*]+?\b(nt_\w+)\s*\(/g)].map(
    (m) => m[1]
  );
  if (names.length === 0) throw new Error("kernels.h declares no NT_KERNEL_API function");
  return names;
}

function emccVersion() {
  const text = execFileSync("emcc", ["--version"], { encoding: "utf8" });
  return text.split("\n")[0].trim();
}

function compile() {
  const dir = mkdtempSync(join(tmpdir(), "nt-kernels-wasm-"));
  try {
    const wasm = join(dir, "kernels.wasm");
    const exports = ["_malloc", "_free", ...exportedKernels().map((n) => `_${n}`)];
    execFileSync(
      "em++",
      [
        ...sources,
        "-I",
        join(root, "include"),
        "-std=c++20",
        "-O3",
        // Rule N6: no fused multiply-add contraction and no fast-math.
        "-ffp-contract=off",
        "-fno-fast-math",
        "-fno-exceptions",
        "-fno-rtti",
        "-sSTANDALONE_WASM=1",
        "--no-entry",
        "-sFILESYSTEM=0",
        "-sALLOW_MEMORY_GROWTH=1",
        "-sINITIAL_MEMORY=16MB",
        "-sMAXIMUM_MEMORY=4GB",
        "-sERROR_ON_UNDEFINED_SYMBOLS=1",
        `-sEXPORTED_FUNCTIONS=${exports.join(",")}`,
        "-o",
        wasm
      ],
      { stdio: ["ignore", "inherit", "inherit"] }
    );
    return readFileSync(wasm);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function render(bytes, version) {
  const base64 = bytes.toString("base64");
  const lines = base64.match(/.{1,100}/g) ?? [];
  return [
    "// Generated by native/kernels/scripts/build-wasm.mjs. Do not edit.",
    `// Compiler: ${version}`,
    `// Size: ${bytes.length} bytes`,
    "",
    "/** The kernel library as a standalone WebAssembly module, base64. */",
    "export const KERNELS_WASM_BASE64 =",
    lines.map((line) => `  "${line}"`).join(" +\n") + ";",
    ""
  ].join("\n");
}

const version = emccVersion();
const text = render(compile(), version);
if (check) {
  const committed = readFileSync(output, "utf8");
  const committedVersion = /\/\/ Compiler: (.*)/.exec(committed)?.[1];
  if (committedVersion !== version) {
    console.log(`skipped: committed module was built by "${committedVersion}", this is "${version}"`);
  } else if (committed !== text) {
    console.error(`${output} is out of date. Run node native/kernels/scripts/build-wasm.mjs`);
    process.exit(1);
  } else {
    console.log("kernels-wasm.ts is up to date");
  }
} else {
  writeFileSync(output, text);
  console.log(`wrote ${output}`);
}
