import { GuestContext } from "../guest/host/context.mjs";
import { forkContext } from "../guest/subgraph-context.mjs";
const check = (value, name) => { if (!value) throw new Error(name); };
const root = new GuestContext({ jobId: "parent" });
root.set("value", "parent-only");
const child = forkContext(root);
check(child.get("value") === "parent-only", "variables copied at fork");
child.set("value", "child-only");
check(root.get("value") === "parent-only", "child variable write isolated");
root.set("later", "parent-later");
check(child.get("later") === undefined, "parent later write isolated");
check(root.signal === child.signal, "shared cancellation signal");
check(root.storage === child.storage && root.assetStorage === child.assetStorage, "same granted storage");
root.registerChannelWriters("same",1);child.registerChannelWriters("same",1);
const rootStream = root.getChannel("same").stream();
const childStream = child.getChannel("same").stream();
const pendingRoot = rootStream.next(), pendingChild = childStream.next();
child.getChannel("same").send("child"); root.getChannel("same").send("root");
check((await pendingChild).value === "child", "child channel isolation");
check((await pendingRoot).value === "root", "parent channel isolation");
root.markChannelWriterDone("same");child.markChannelWriterDone("same");
check((await rootStream.next()).done && (await childStream.next()).done, "separate channel EOS");
globalThis.G6_RESULTS=JSON.stringify({variableIsolation:true,channelIsolation:true,sharedGrants:true});
globalThis.__nodetool={};
