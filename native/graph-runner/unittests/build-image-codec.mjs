import { build } from 'esbuild';
import { textEncodingBanner } from '../guest/text-encoding-banner.mjs';
import { writeFile, mkdir, symlink, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import sharp from 'sharp';
import { imageNodePlugin } from '../guest/host/image-node-plugin.mjs';
import { capabilityPlugins } from '../guest/host/plugins.mjs';
import { parityPlugins } from '../guest/parity/profile.mjs';
import { hostModulesPlugin } from '../guest/host-modules.mjs';
import { LIB_IMAGE_DRAW_NODES } from '@nodetool-ai/image-nodes/nodes/lib-image-draw';
const output = process.argv[2];
await mkdir(output, { recursive: true });
const rgba = (w, h, salt) => Uint8Array.from({ length: w*h*4 }, (_, i) => i % 4 === 3 ? [0,1,127,254,255][Math.floor(i/4)%5] : (i*47 + salt*31) % 256);
const fixtures = [];
for (const [w,h,fw,fh,mw,mh] of [[3,2,2,3,1,2],[1,1,3,2,2,3],[2,3,7,5,5,7],[7,5,2,3,3,2]]) {
  const base = await sharp(rgba(w,h,1), {raw:{width:w,height:h,channels:4}}).png().toBuffer();
  const foreground = await sharp(rgba(fw,fh,2), {raw:{width:fw,height:fh,channels:4}}).png().toBuffer();
  const mask = await sharp(rgba(mw,mh,3), {raw:{width:mw,height:mh,channels:4}}).png().toBuffer();
  const Mask = LIB_IMAGE_DRAW_NODES.find(c => c.nodeType === 'lib.image.Mask');
  const node = new Mask({id:'mask'});
  const ref = data => ({type:'image',data, mimeType:'image/png'});
  node.image1 = ref(base); node.image2 = ref(foreground); node.mask = ref(mask);
  const result = await node.process();
  const encoded = Buffer.from(result.output.data, 'base64');
  const expected = await sharp(encoded).ensureAlpha().raw().toBuffer();
  const grey = await sharp(mask).resize(w,h,{fit:'fill'}).greyscale().raw().toBuffer();
  const resized = await sharp(foreground).resize(w,h,{fit:'fill'}).ensureAlpha().raw().toBuffer();
  const webp = await sharp(base).webp({lossless:true}).toBuffer();
  const lossy = await sharp(base).webp().toBuffer();
  const lossyRaw = await sharp(lossy).ensureAlpha().raw().toBuffer();
  const webpRaw = await sharp(webp).ensureAlpha().raw().toBuffer();
  fixtures.push({w,h,base:[...base],foreground:[...foreground],mask:[...mask],expected:[...expected],grey:[...grey],resized:[...resized],webp:[...webp],webpRaw:[...webpRaw],lossy:[...lossy],lossyRaw:[...lossyRaw]});
}
const textBase = await sharp({create:{width:64,height:32,channels:4,background:{r:31,g:71,b:3,alpha:0.5}}}).png().toBuffer();
const Text = LIB_IMAGE_DRAW_NODES.find(c => c.nodeType === 'lib.image.draw.RenderText');
const textNode = new Text({id:'text'});
textNode.image = {type:'image',data:textBase,mimeType:'image/png'};
textNode.text = 'Ab<&'; textNode.size = 12;
const textOutput = await textNode.process();
fixtures[0].textBase = [...textBase];
fixtures[0].textExpected = [...await sharp(Buffer.from(textOutput.output.data,'base64')).ensureAlpha().raw().toBuffer()];
await unlink(join(output,'escape.png')).catch(error => { if (error.code !== 'ENOENT') throw error; });
await symlink('/etc/passwd', join(output,'escape.png'));
await writeFile(join(output, 'base.webp'), new Uint8Array(fixtures[0].webp));
await writeFile(join(output, 'base.png'), new Uint8Array(fixtures[0].base));
await writeFile(join(output, 'fixtures.json'), JSON.stringify(fixtures));
const beforePlugin = process.argv[3] ? [{name:'before-sharp',setup(b) {
  b.onResolve({filter:/sharp\.mjs$/}, () => ({path:process.argv[3]}));
}}] : [];
await build({banner:{js:textEncodingBanner},entryPoints:[fileURLToPath(new URL('./image-codec.test.mjs',import.meta.url))], outfile:join(output,'test.js'), bundle:true,format:'esm',platform:'browser',target:'es2022',plugins:[imageNodePlugin(),...beforePlugin,...capabilityPlugins(),hostModulesPlugin(),...await parityPlugins({modules:[]})]});
