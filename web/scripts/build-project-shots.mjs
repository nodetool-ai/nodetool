// Converts the project-view documentation screenshots into the marketing
// site's copies.
//
//   node scripts/build-project-shots.mjs [--check]
//
// The source PNGs come from the documentation screenshot suite
// (`npm run screenshots` in web/, tests/benchmarks/screenshots.spec.ts), which
// drives the real app against the seeded backend in
// packages/websocket/src/screenshot-projects.ts. This script only re-encodes
// them: WebP at the same pixel size, into marketing/public/projects/, plus
// marketing/src/data/projectShots.generated.ts with the intrinsic size
// `next/image` needs.
//
// Splitting the two keeps the expensive half (a browser, a backend, a seeded
// database) out of a marketing rebuild: re-encoding is deterministic and needs
// neither. `--check` re-encodes into memory and fails when a committed file or
// a recorded size has drifted, so a stale copy cannot ship unnoticed.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = path.resolve(WEB, "..");
const SOURCE_DIR = path.join(ROOT, "docs/assets/screenshots");
const OUT_DIR = path.join(ROOT, "marketing/public/projects");
const MANIFEST = path.join(
  ROOT,
  "marketing/src/data/projectShots.generated.ts"
);

/**
 * One entry per shot the landing page uses.
 *
 * `height` crops the shot to its top band. The docs gallery wants the whole
 * 1440×900 screen; the landing page wants the part that carries the claim. The
 * new-project surface pins its blank-document strip to the bottom of the
 * viewport, so at 900px there is 270px of empty column between the prompt and
 * that strip — dead space that reads as an empty product. Cropping removes
 * only that: nothing is composited, moved, or re-rendered.
 */
const SHOTS = [
  { id: "project-new", height: 520 },
  { id: "project-overview" },
  { id: "project-list" },
];

const QUALITY = 88;

const check = process.argv.includes("--check");

async function encode({ id, height: cropHeight }) {
  const source = path.join(SOURCE_DIR, `${id}.png`);
  if (!fs.existsSync(source)) {
    throw new Error(
      `Missing ${path.relative(ROOT, source)} — run \`npm run screenshots\` in web/ first.`
    );
  }
  const pipeline = sharp(source);
  const meta = await pipeline.metadata();
  if (cropHeight && cropHeight > meta.height) {
    throw new Error(
      `${id}.png is ${meta.height}px tall — cannot crop it to ${cropHeight}px`
    );
  }
  const width = meta.width;
  const height = cropHeight ?? meta.height;
  if (cropHeight) {
    pipeline.extract({ left: 0, top: 0, width, height });
  }
  const webp = await pipeline.webp({ quality: QUALITY }).toBuffer();
  return { id, width, height, webp };
}

const shots = [];
for (const shot of SHOTS) {
  shots.push(await encode(shot));
}

const manifest = `// Generated by web/scripts/build-project-shots.mjs. Do not edit.
export interface ProjectShot {
  id: string;
  width: number;
  height: number;
}

export const PROJECT_SHOTS: ProjectShot[] = ${JSON.stringify(
  shots.map(({ id, width, height }) => ({ id, width, height })),
  null,
  2
)};
`;

if (check) {
  const stale = [];
  for (const shot of shots) {
    const target = path.join(OUT_DIR, `${shot.id}.webp`);
    if (!fs.existsSync(target)) {
      stale.push(`${path.relative(ROOT, target)} is missing`);
      continue;
    }
    // Byte equality: the encoder is deterministic for a given source and
    // quality, so a difference means the source screenshot moved on.
    if (!fs.readFileSync(target).equals(shot.webp)) {
      stale.push(`${path.relative(ROOT, target)} differs from its source PNG`);
    }
  }
  if (fs.readFileSync(MANIFEST, "utf8") !== manifest) {
    stale.push(`${path.relative(ROOT, MANIFEST)} does not match the shots`);
  }
  if (stale.length > 0) {
    console.error("Project shots are stale:");
    for (const line of stale) console.error(`  · ${line}`);
    console.error("Re-run: npm run project-shots (in web/)");
    process.exit(1);
  }
  console.log(`✓ ${shots.length} project shots are up to date`);
} else {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const shot of shots) {
    const target = path.join(OUT_DIR, `${shot.id}.webp`);
    fs.writeFileSync(target, shot.webp);
    console.log(
      `✓ ${path.relative(ROOT, target)} (${shot.width}×${shot.height}, ${Math.round(
        shot.webp.length / 1024
      )} kB)`
    );
  }
  fs.writeFileSync(MANIFEST, manifest);
  console.log(`✓ ${path.relative(ROOT, MANIFEST)}`);
}
