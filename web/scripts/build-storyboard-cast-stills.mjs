// Builds the keyframe stills the storyboard demo cast embeds.
//
//   node scripts/build-storyboard-cast-stills.mjs
//
// Reads the six SCRAPHEART shots already shipped for the marketing site and
// writes them into src/demo/assets/storyboardStills.ts as base64 JPEG data
// URIs — the same "inline so replay needs no asset resolution" pattern as
// exampleImage.ts and cookbookImages.ts. The cards render about 300 px wide,
// so 480×270 at q72 is generous and keeps the module near 200 KB.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SHOTS = path.resolve(WEB, "../marketing/public");
const OUT = path.join(WEB, "src/demo/assets/storyboardStills.ts");

/** One per `trailer-shot-<n>.png`, in cut order. */
const STILLS = [
  { name: "DEAD_ENGINE", shot: "the engine block blows out over the salt" },
  { name: "THE_CHAIN", shot: "a rider swings a chain at the chase truck" },
  { name: "THE_ROLLOVER", shot: "a wheel churns rock as the truck goes over" },
  { name: "THE_BIKE", shot: "the bike cuts through the ruins" },
  { name: "THE_CUT", shot: "an angle grinder throws sparks across the wreck" },
  { name: "THE_GETAWAY", shot: "the car breaks away across open flats" },
];

const uris = [];
for (const [i, still] of STILLS.entries()) {
  const src = path.join(SHOTS, `trailer-shot-${i + 1}.png`);
  if (!fs.existsSync(src)) throw new Error(`Missing shot: ${src}`);
  const jpeg = await sharp(src)
    .resize(480, 270, { fit: "cover" })
    .jpeg({ quality: 72, mozjpeg: true })
    .toBuffer();
  uris.push([still, `data:image/jpeg;base64,${jpeg.toString("base64")}`]);
}

const body = uris
  .map(
    ([still, uri]) =>
      `/** SCRAPHEART — ${still.shot}. */\n` +
      `export const ${still.name}_STILL =\n  "${uri}";\n`
  )
  .join("\n");

fs.writeFileSync(
  OUT,
  `/**\n` +
    ` * Keyframe stills for the storyboard demo cast — the six SCRAPHEART shots,\n` +
    ` * inlined as base64 JPEG data URIs so the cast replays with no asset\n` +
    ` * resolution, no backend, and no render credits.\n` +
    ` *\n` +
    ` * Generated by web/scripts/build-storyboard-cast-stills.mjs. Do not edit.\n` +
    ` */\n\n` +
    body +
    `\n/** The six stills in cut order. */\nexport const STORYBOARD_STILLS = [\n` +
    uris.map(([still]) => `  ${still.name}_STILL`).join(",\n") +
    `,\n] as const;\n`
);

const kb = Math.round(fs.statSync(OUT).size / 1024);
console.log(`✓ ${path.relative(WEB, OUT)} (${uris.length} stills, ${kb} KB)`);
