#!/usr/bin/env node
/**
 * Write `src/components/timeline/fonts.css` from the bundled font catalog.
 *
 * The rules are generated because a face added to
 * `packages/timeline/src/fonts/catalog.ts` and forgotten here renders as the
 * fallback in the editor and as the real face in every other host — the
 * divergence the corpus exists to remove (D8, F15).
 *
 * `--check` writes nothing and exits non-zero when the checked-in file has
 * drifted, which is what `web/src/components/timeline/__tests__/fonts.css.test.ts`
 * asserts too; this is the form for a shell.
 *
 *   node scripts/generate-timeline-fonts-css.mjs [--check]
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { bundledFontFaceCss } from "@nodetool-ai/timeline";

const HERE = dirname(fileURLToPath(import.meta.url));
const TARGET = join(HERE, "..", "src", "components", "timeline", "fonts.css");

const HEADER = `/* Generated by web/scripts/generate-timeline-fonts-css.mjs — do not edit.
 * Source: BUNDLED_FONTS in packages/timeline/src/fonts/catalog.ts.
 * Regenerate: node scripts/generate-timeline-fonts-css.mjs
 */
`;

const wanted = `${HEADER}\n${bundledFontFaceCss()}`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(TARGET, "utf8");
  } catch {
    // Absent counts as drifted; the message below says what to run.
  }
  if (current !== wanted) {
    console.error(
      "timeline fonts.css is stale — run " +
        "`node scripts/generate-timeline-fonts-css.mjs` in web/."
    );
    process.exit(1);
  }
  console.log("timeline fonts.css is up to date");
} else {
  writeFileSync(TARGET, wanted);
  console.log(`wrote ${TARGET}`);
}
