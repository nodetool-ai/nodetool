/**
 * Writes FableSynth's factory presets into @nodetool-ai/timeline.
 *
 *   npm run fablesynth-presets          # write the file
 *   npm run fablesynth-presets:check    # fail if the file is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { buildFablesynthFactoryPresets } from "../src/components/timeline/daw/devices/fablesynthFactoryPresets";

const OUT = fileURLToPath(
  new URL("../../packages/timeline/src/midi/fablesynthPresets.gen.ts", import.meta.url)
);

const source = `// Generated by web/scripts/generate-fablesynth-presets.ts. Do not edit.
// Run \`npm run fablesynth-presets\` in web/ after changing a FableSynth preset.

import type { MidiInstrumentPreset } from "./presets.js";

export const FABLESYNTH_FACTORY_PRESETS: readonly MidiInstrumentPreset[] = [
${buildFablesynthFactoryPresets()
  .map((preset) => `  ${JSON.stringify(preset)}`)
  .join(",\n")}
];
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // A missing file is stale too.
  }
  if (current !== source) {
    console.error(`${OUT} is stale. Run npm run fablesynth-presets in web/.`);
    process.exit(1);
  }
} else {
  writeFileSync(OUT, source);
  console.log(`Wrote ${OUT}`);
}
