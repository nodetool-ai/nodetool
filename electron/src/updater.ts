import { app, Notification } from "electron";
import { autoUpdater, ProgressInfo, UpdateInfo } from "electron-updater";
import log from "electron-log";
import path from "path";
import fs from "fs";
import { logMessage } from "./logger";
import { getMainWindow } from "./state";
import { IpcChannels } from "./types.d";
import {
  getDefaultUpdateChannel,
  getUpdateChannel,
  readSettingsAsync,
} from "./settings";
import { errorMessage } from "./utils";

/** How often a running app checks for a newer release after the launch check. */
const UPDATE_CHECK_INTERVAL_MS = 4 * 60 * 60 * 1000;

let eventsRegistered = false;
let checkTimer: NodeJS.Timeout | null = null;
let updateDownloaded = false;
let quittingForUpdate = false;

/**
 * Auto-updater Module
 *
 * This module handles automatic updates for the Nodetool application using electron-updater.
 * It connects to GitHub releases to check for and download new versions of the application.
 *
 * Key Features:
 * - Checks for updates when the app starts and every few hours while it runs
 * - Downloads updates in the background
 * - Notifies the user through the main window when updates are available
 * - Provides download progress information
 * - Handles update errors gracefully
 *
 * Update Process:
 * 1. Checks GitHub releases for new versions
 * 2. If an update is found, notifies the user with the new version and release URL
 * 3. Downloads the update in the background, showing progress
 * 4. Once downloaded, notifies the user that the update is ready
 *
 * Configuration:
 * - Updates are only checked in packaged mode (not in development)
 * - Updates are fetched from the nodetool-ai/nodetool GitHub repository
 * - Update cache is stored in "nodetool-updater" directory
 *
 * Error Handling:
 * - Gracefully handles missing app-update.yml file
 * - Logs warnings instead of crashing
 * - Skips auto-update when not in packaged mode
 */

/**
 * Checks if the app-update.yml file exists in the expected location
 * This file is required by electron-updater and is generated by electron-builder
 * @returns true if the file exists, false otherwise
 */
function isAppUpdateConfigPresent(): boolean {
  try {
    // In packaged apps, the app-update.yml is in the resources directory (next to app.asar)
    // The exact location varies by platform but is always at process.resourcesPath
    const resourcesPath = process.resourcesPath;
    const appUpdateYmlPath = path.join(resourcesPath, "app-update.yml");
    
    // Normalize path to handle any Windows path issues (e.g., \r or other control characters)
    const normalizedPath = path.normalize(appUpdateYmlPath);
    
    const exists = fs.existsSync(normalizedPath);
    if (!exists) {
      logMessage(
        `app-update.yml not found at expected path: ${normalizedPath}`,
        "warn"
      );
    }
    return exists;
  } catch (err) {
    logMessage(
      `Error checking for app-update.yml: ${errorMessage(err)}`,
      "warn"
    );
    return false;
  }
}

/**
 * Checks if an error is related to missing app-update.yml configuration file
 * @param err - The error to check
 * @returns true if the error indicates a missing app-update.yml file
 */
function isMissingAppUpdateConfigError(err: Error): boolean {
  return err.message.includes("ENOENT") && err.message.includes("app-update.yml");
}

/**
 * Checks if auto-updates are enabled in settings.
 * Auto-updates are opt-in by default (disabled unless explicitly enabled).
 * @returns Promise resolving to true if auto-updates are enabled, false otherwise
 */
async function isAutoUpdatesEnabledAsync(): Promise<boolean> {
  try {
    const settings = await readSettingsAsync();
    // Auto-updates are opt-in, so default to false if not set
    return settings.autoUpdatesEnabled === true;
  } catch (err) {
    logMessage(
      `Error reading auto-updates setting: ${errorMessage(err)}`,
      "warn"
    );
    return false;
  }
}

function checkForUpdates(): void {
  autoUpdater.checkForUpdates().catch((err: Error) => {
    // Handle specific error for missing app-update.yml more gracefully
    if (isMissingAppUpdateConfigError(err)) {
      logMessage(
        "Auto-update check skipped: app-update.yml not found. " +
        "Please reinstall from GitHub releases to enable auto-updates.",
        "warn"
      );
    } else {
      logMessage(`Failed to check for updates: ${err.message}`, "warn");
    }
  });
}

/**
 * Re-checks while the app runs, since it can stay open in the tray for days.
 * Stops once an update has been downloaded: it installs on the next quit.
 */
function startPeriodicChecks(): void {
  if (checkTimer || updateDownloaded) {
    return;
  }
  checkTimer = setInterval(checkForUpdates, UPDATE_CHECK_INTERVAL_MS);
  checkTimer.unref();
}

function stopPeriodicChecks(): void {
  if (checkTimer) {
    clearInterval(checkTimer);
    checkTimer = null;
  }
}

/**
 * Sets up the auto-updater, or applies changed update settings to a running
 * one. Safe to call again after the user toggles auto-updates or switches the
 * update channel.
 */
async function setupAutoUpdater(): Promise<void> {
  // Skip auto-update in development mode
  if (!app.isPackaged) {
    logMessage("Skipping auto-updater in development mode");
    return;
  }

  // Check if auto-updates are enabled (opt-in)
  const autoUpdateEnabled = await isAutoUpdatesEnabledAsync();
  if (!autoUpdateEnabled) {
    logMessage("Auto-updates disabled by user preference (opt-in required)");
    stopPeriodicChecks();
    autoUpdater.autoDownload = false;
    autoUpdater.autoInstallOnAppQuit = false;
    return;
  }

  // Check if the required app-update.yml file exists
  // This file is generated by electron-builder and is required by electron-updater
  if (!isAppUpdateConfigPresent()) {
    logMessage(
      "Auto-update disabled: app-update.yml configuration file is missing. " +
      "This may occur on older installations. Please reinstall the application " +
      "from GitHub releases to enable auto-updates: " +
      "https://github.com/nodetool-ai/nodetool/releases",
      "warn"
    );
    return;
  }

  try {
    const settings = await readSettingsAsync();
    const currentVersion = app.getVersion();
    const updateChannel = getUpdateChannel(settings, currentVersion);
    const allowPrerelease = updateChannel === "nightly";

    autoUpdater.channel = updateChannel;
    autoUpdater.allowPrerelease = allowPrerelease;
    // The channel setter turns downgrades on. Keep them only after a channel
    // switch, where the other channel's newest build can be older, so a
    // re-published older release cannot roll back users on their own channel.
    autoUpdater.allowDowngrade =
      updateChannel !== getDefaultUpdateChannel(currentVersion);
    autoUpdater.autoDownload = true;
    autoUpdater.autoInstallOnAppQuit = true;
    const feedUrl = {
      provider: "github",
      owner: "nodetool-ai",
      repo: "nodetool",
      updaterCacheDirName: "nodetool-updater",
    } as const;
    autoUpdater.setFeedURL(
      updateChannel === "nightly" ? { ...feedUrl, channel: "nightly" } : feedUrl
    );

    logMessage(
      `Auto-updater using ${updateChannel} channel (allowPrerelease=${allowPrerelease})`
    );
    autoUpdater.logger = log;

    setupAutoUpdaterEvents();
    checkForUpdates();
    startPeriodicChecks();
  } catch (err) {
    // Catch any synchronous errors during setup
    logMessage(
      `Failed to initialize auto-updater: ${errorMessage(err)}`,
      "warn"
    );
  }
}

/**
 * Sets up the auto-updater events
 */
function setupAutoUpdaterEvents(): void {
  if (eventsRegistered) {
    return;
  }
  eventsRegistered = true;

  autoUpdater.on("checking-for-update", () => {
    logMessage("Checking for updates...");
  });

  autoUpdater.on("update-available", (info: UpdateInfo) => {
    try {
      logMessage(`Update available: ${info.version}`);
      const mainWindow = getMainWindow();
      if (mainWindow) {
        const releaseUrl = `https://github.com/nodetool-ai/nodetool/releases/tag/v${info.version}`;
        mainWindow.webContents.send(IpcChannels.UPDATE_AVAILABLE, {
          version: info.version,
          releaseUrl,
          downloaded: false,
        });
      }

      if (Notification.isSupported()) {
        const notification = new Notification({
          title: "NodeTool Update Available",
          body: `Version ${info.version} is available. Downloading in the background...`,
        });
        notification.on("click", () => {
          const win = getMainWindow();
          if (win) {
            if (win.isMinimized()) win.restore();
            win.show();
            win.focus();
          }
        });
        notification.show();
      }
    } catch (err) {
      logMessage(
        `Error handling update-available event: ${errorMessage(err)}`,
        "error"
      );
    }
  });

  autoUpdater.on("update-not-available", () => {
    logMessage("No updates available");
  });

  autoUpdater.on("download-progress", (progress: ProgressInfo) => {
    try {
      const mainWindow = getMainWindow();
      if (mainWindow) {
        mainWindow.webContents.send(IpcChannels.UPDATE_PROGRESS, progress);
      }
    } catch (err) {
      logMessage(
        `Error handling download progress: ${errorMessage(err)}`,
        "error"
      );
    }
  });

  autoUpdater.on("update-downloaded", async (info: UpdateInfo) => {
    try {
      logMessage(`Update downloaded: ${info.version}`);
      updateDownloaded = true;
      stopPeriodicChecks();

      const mainWindow = getMainWindow();
      if (mainWindow) {
        const releaseUrl = `https://github.com/nodetool-ai/nodetool/releases/tag/v${info.version}`;
        mainWindow.webContents.send(IpcChannels.UPDATE_AVAILABLE, {
          version: info.version,
          releaseUrl,
          downloaded: true,
        });
      }

      // Show native notification
      if (Notification.isSupported()) {
        const notification = new Notification({
          title: "NodeTool Update Ready",
          body: `Version ${info.version} has been downloaded. Click to restart and install.`,
        });
        notification.on("click", () => {
          logMessage("User clicked update notification — restarting to install");
          quitAndInstallUpdate();
        });
        notification.show();
      }
    } catch (err) {
      logMessage(
        `Error handling update-downloaded event: ${errorMessage(err)}`,
        "error"
      );
    }
  });

  autoUpdater.on("error", (err: Error) => {
    // Handle missing app-update.yml error more gracefully
    if (isMissingAppUpdateConfigError(err)) {
      logMessage(
        "Auto-update error: app-update.yml not found. " +
        "This is expected on older installations. " +
        "Please reinstall from GitHub releases to enable auto-updates.",
        "warn"
      );
      // Don't send error to window for missing config - it's not actionable by the user
      return;
    }

    logMessage(`Update error: ${err.message}`, "error");
  });
}

/**
 * Restarts into the downloaded update. Does nothing until one is downloaded,
 * so a stray request cannot quit the app.
 */
function quitAndInstallUpdate(): void {
  if (!updateDownloaded) {
    logMessage("Install requested but no update has been downloaded", "warn");
    return;
  }
  quittingForUpdate = true;
  autoUpdater.quitAndInstall();
}

/**
 * True once a restart into a downloaded update has started. On macOS the
 * updater closes every window first, which must not open the close dialog.
 */
function isQuittingForUpdate(): boolean {
  return quittingForUpdate;
}

export { setupAutoUpdater, quitAndInstallUpdate, isQuittingForUpdate };
