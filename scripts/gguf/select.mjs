/**
 * Pure selection logic for `sync-gguf-trending.mjs`: which trending Hugging
 * Face GGUF repos the llama.cpp provider offers, which file of each one it
 * downloads, and the TypeScript module it writes. No network here, so the
 * tests drive it with fixed API responses.
 */

const SPLIT_FILE = /-\d{5}-of-\d{5}\.gguf$/i;

/** The publisher part of a repo id. */
const publisherOf = (repoId) => repoId.split("/")[0];

/**
 * The key two repos of one base model share: the repo name without the
 * publisher, a `GGUF` or `MTP` suffix and case. `unsloth/LFM2.5-24B-A2B-GGUF`
 * and `LiquidAI/LFM2.5-24B-A2B-GGUF` both give `lfm2.5-24b-a2b`. The runtime
 * applies the same key in `listedChatGgufs`.
 */
export function modelKey(repoId) {
  const name = repoId.split("/")[1] ?? repoId;
  return name
    .replace(/[-_.]?gguf$/i, "")
    .replace(/[-_.]?mtp$/i, "")
    .toLowerCase();
}

/** Whether a listed repo passes the publisher, word and task rules. */
export function isCandidate(repo, rules) {
  const publishers = new Set(rules.publishers.map((p) => p.toLowerCase()));
  if (!publishers.has(publisherOf(repo.id).toLowerCase())) {
    return false;
  }
  const id = repo.id.toLowerCase();
  if (rules.blockedWords.some((word) => id.includes(word.toLowerCase()))) {
    return false;
  }
  // A text-to-image repo can carry a language-model text encoder, so the
  // task decides first. An untagged repo counts when its header is a chat model.
  if (repo.pipeline_tag && !rules.pipelineTags.includes(repo.pipeline_tag)) {
    return false;
  }
  return typeof repo.gguf?.context_length === "number";
}

/** Bytes per parameter below which a file cannot hold the whole model at 4 bits. */
const MIN_BYTES_PER_PARAM = 0.4;

/**
 * The file to download from a repo's file list: the first quantization in
 * the preference order, as one file under the size cap. Split files and
 * vision projectors are skipped. With the repo's parameter count, a file too
 * small to hold the model is skipped too, such as a speculative-decoding
 * draft head. Null when no file fits.
 */
export function pickFile(files, rules, paramCount = 0) {
  const maxBytes = rules.maxSizeGb * 1e9;
  const minBytes = paramCount * MIN_BYTES_PER_PARAM;
  const ggufs = files.filter(
    (f) =>
      f.type === "file" &&
      f.path.toLowerCase().endsWith(".gguf") &&
      !f.path.toLowerCase().includes("mmproj") &&
      !SPLIT_FILE.test(f.path)
  );
  for (const quant of rules.quantPreference) {
    const match = new RegExp(`[-_.]${quant}\\.gguf$`, "i");
    const file = ggufs
      .filter((f) => match.test(f.path))
      .map((f) => ({ path: f.path, size: f.lfs?.size ?? f.size ?? 0 }))
      .filter((f) => f.size > 0 && f.size >= minBytes && f.size <= maxBytes)
      .sort((a, b) => a.path.length - b.path.length)[0];
    if (file) {
      return file;
    }
  }
  return null;
}

/** A display name from the repo name and the file size: `LFM2.5 24B A2B (14.4 GB)`. */
export function displayName(repoId, sizeBytes) {
  const base = (repoId.split("/")[1] ?? repoId)
    .replace(/[-_.]?gguf$/i, "")
    .replace(/[-_]+/g, " ")
    .trim();
  const gb = sizeBytes / 1e9;
  const size = gb >= 1 ? `${gb.toFixed(1)} GB` : `${Math.round(gb * 1000)} MB`;
  return `${base} (${size})`;
}

/**
 * Pick the trending models: walk the repos in trending order, keep the
 * candidates, one per base model, until `maxModels` have a file that fits.
 * `filesFor` returns a repo's file list. The result records why each other
 * repo was skipped, for the run report.
 */
export async function selectTrending(repos, rules, filesFor) {
  const models = [];
  const skipped = [];
  const keys = new Set();
  for (const repo of repos) {
    if (models.length >= rules.maxModels) {
      break;
    }
    if (!isCandidate(repo, rules)) {
      skipped.push({ repoId: repo.id, reason: "rules" });
      continue;
    }
    const key = modelKey(repo.id);
    if (keys.has(key)) {
      skipped.push({ repoId: repo.id, reason: "duplicate" });
      continue;
    }
    const file = pickFile(await filesFor(repo.id), rules, repo.gguf?.total ?? 0);
    if (!file) {
      skipped.push({ repoId: repo.id, reason: "no file fits" });
      continue;
    }
    keys.add(key);
    models.push({ repoId: repo.id, file: file.path, name: displayName(repo.id, file.size) });
  }
  return { models, skipped };
}

/** The generated TypeScript module. Stable output: no timestamp. */
export function renderModule(models) {
  const entries = models
    .map(
      (m) =>
        `  {\n    repoId: ${JSON.stringify(m.repoId)},\n    file: ${JSON.stringify(m.file)},\n    name: ${JSON.stringify(m.name)}\n  }`
    )
    .join(",\n");
  return `// Generated by scripts/sync-gguf-trending.mjs from the trending GGUF repos on
// Hugging Face. Do not edit by hand: the nightly workflow rewrites this file.
// Change the selection rules in scripts/gguf/sources.json.
import type { RecommendedGguf } from "./node-llama-cpp-models.js";

export const TRENDING_CHAT_GGUFS: readonly RecommendedGguf[] = [${entries ? `\n${entries}\n` : ""}];
`;
}
