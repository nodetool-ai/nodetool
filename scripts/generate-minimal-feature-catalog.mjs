import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const supplementalDescriptors = [{
  id: "provider-anthropic",
  apiVersion: 1,
  requires: [],
  capabilities: ["provider:anthropic"],
  nodeTypes: ["anthropic.text.ChatComplete"]
}];
const catalog = JSON.parse(await readFile(new URL("packages/node-catalog/dist/index.json", root), "utf8"));
const owners = Object.entries(catalog.owners);
if (!owners.length || !catalog.packs.length) {
  throw new Error("Node catalog must contain packs and node ownership entries");
}
const nodeTypes = new Map();
for (const [type, owner] of owners) {
  const types = nodeTypes.get(owner) ?? [];
  types.push(type);
  nodeTypes.set(owner, types);
}
const descriptors = catalog.packs.filter((pack) => pack.kind === "core" || pack.kind === "node-pack").map((pack) => ({
  id: pack.id,
  apiVersion: 1,
  requires: pack.requires,
  capabilities: [`nodes:${pack.id}`],
  nodeTypes: (nodeTypes.get(pack.id) ?? []).sort()
}));
for (const descriptor of supplementalDescriptors) {
  if (descriptors.some(existing => existing.id === descriptor.id)) {
    throw new Error(`Supplemental feature ${descriptor.id} already exists in the node catalog`);
  }
  for (const nodeType of descriptor.nodeTypes) {
    if (catalog.owners[nodeType]) {
      throw new Error(`Supplemental node ${nodeType} already has a node catalog owner`);
    }
  }
  descriptors.push(descriptor);
}
const output = `// Generated by node scripts/generate-minimal-feature-catalog.mjs after building node-catalog.\nimport type { FeatureDescriptor } from "@nodetool-ai/server-features";\n\nexport const OPTIONAL_FEATURE_CATALOG: readonly FeatureDescriptor[] = ${JSON.stringify(descriptors, null, 2)};\n`;
const destination = new URL("packages/server-minimal/src/feature-catalog.ts", root);
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== output) {
    throw new Error(`Feature catalog drift: run node ${fileURLToPath(import.meta.url)}`);
  }
} else {
  await writeFile(destination, output);
}
