#!/usr/bin/env node
/**
 * Regenerates packages/runtime/src/providers/comfy-router-manifest.ts from each
 * catalog model's OpenAPI document.
 *
 *   COMFY_API_KEY=... node scripts/generate-comfy-router-manifest.mjs
 *   node scripts/generate-comfy-router-manifest.mjs --schemas <dir>
 *   node scripts/generate-comfy-router-manifest.mjs --check
 *
 * `--schemas` reads saved `<provider>__<model>.json` documents. `--check` writes
 * nothing and exits 1 when the committed manifest differs.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildManifestEntry } from "./comfy-router-manifest-lib.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CATALOG = join(ROOT, "packages/runtime/src/providers/comfy-router-catalog.ts");
const OUT = join(ROOT, "packages/runtime/src/providers/comfy-router-manifest.ts");
const BASE = process.env.COMFY_ROUTER_URL ?? "https://api.comfy.org";

const args = process.argv.slice(2);
const schemasDir = args.includes("--schemas") ? args[args.indexOf("--schemas") + 1] : null;
const check = args.includes("--check");

async function loadDocument(id) {
  if (schemasDir) {
    return JSON.parse(await readFile(join(schemasDir, `${id.replace("/", "__")}.json`), "utf8"));
  }
  const key = process.env.COMFY_API_KEY;
  if (!key) throw new Error("Set COMFY_API_KEY or pass --schemas <dir>.");
  const res = await fetch(`${BASE}/v2/models/${id}/openapi.json`, { headers: { "X-API-Key": key } });
  if (!res.ok) throw new Error(`GET ${id}: HTTP ${res.status}`);
  return res.json();
}

const catalog = await readFile(CATALOG, "utf8");
const ids = [...catalog.matchAll(/\{ id: "([^"]+)", kind:/g)].map((match) => match[1]);
if (ids.length === 0) throw new Error("No models found in comfy-router-catalog.ts.");

const manifest = {};
for (const id of ids) {
  const entry = buildManifestEntry(await loadDocument(id));
  if (Object.keys(entry.params).length > 0 || entry.unparsed.length > 0) manifest[id] = entry;
}

const output = `/**
 * What each Comfy Router model accepts for size, aspect ratio, resolution and
 * duration, normalized from its OpenAPI document.
 *
 * Generated by \`scripts/generate-comfy-router-manifest.mjs\`. Do not edit by
 * hand. \`unparsed\` names a field whose accepted values could not be read, and
 * such a field is not constrained.
 */

export interface RouterParamSpec {
  field: string;
  source: "enum" | "schema" | "description";
  values?: string[];
  min?: number;
  max?: number;
  separator?: "*" | "x";
  pixelArea?: [number, number];
}

export interface RouterManifestEntry {
  params: Partial<Record<"resolution" | "aspectRatio" | "size" | "duration", RouterParamSpec>>;
  unparsed: string[];
}

export const COMFY_ROUTER_MANIFEST: Record<string, RouterManifestEntry> = ${JSON.stringify(manifest, null, 2)};
`;

const unparsed = Object.values(manifest).reduce((sum, entry) => sum + entry.unparsed.length, 0);
console.log(`models: ${ids.length}, with constraints: ${Object.keys(manifest).length}, unparsed fields: ${unparsed}`);
if (check) {
  const current = await readFile(OUT, "utf8").catch(() => "");
  if (current !== output) {
    console.error("comfy-router-manifest.ts differs from the live schemas. Regenerate it.");
    process.exit(1);
  }
} else {
  await writeFile(OUT, output);
}
