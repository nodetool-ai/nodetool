describe("generate_media RPC (parameter passthrough)", () => {
  let ws: MockWebSocket;
  const captured = {
    textToImages: [] as Array<{ params: TextToImageParams; variations: number }>,
    imageToImages: [] as Array<{
      images: Uint8Array[];
      params: ImageToImageParams;
      variations: number;
    }>,
    inpaintImages: [] as Array<{
      images: Uint8Array[];
      params: Record<string, unknown>;
      variations: number;
    }>,
    ttsEncoded: [] as Array<Record<string, unknown>>
  };

  const configureAssets = (ids: string[]): void => {
    const byId = new Map<string, ReturnType<typeof makeAssetRow>>();
    for (const id of ids) {
      byId.set(id, makeAssetRow(id, null));
      REF_BYTES[id] = new Uint8Array([0xc1, ...Buffer.from(id)]);
    }
    (Asset as unknown as { find: typeof vi.fn }).find.mockImplementation(
      async (_userId: string, assetId: string) => byId.get(assetId) ?? null
    );
  };

  const makeProvider = (): never =>
    ({
      provider: "fake",
      async textToImages(
        params: TextToImageParams,
        variations = 1
      ): Promise<Uint8Array[]> {
        captured.textToImages.push({ params, variations });
        return [new Uint8Array([0x89, 0x50, 0x4e, 0x47])];
      },
      async imageToImages(
        images: Uint8Array[],
        params: ImageToImageParams,
        variations = 1
      ): Promise<Uint8Array[]> {
        captured.imageToImages.push({ images, params, variations });
        return [new Uint8Array([0x89, 0x50, 0x4e, 0x47])];
      },
      async inpaintImages(
        images: Uint8Array[],
        params: unknown,
        variations = 1
      ): Promise<Uint8Array[]> {
        captured.inpaintImages.push({
          images,
          params: params as Record<string, unknown>,
          variations
        });
        return [new Uint8Array([0x89, 0x50, 0x4e, 0x47])];
      },
      async textToSpeechEncoded(
        args: Record<string, unknown>
      ): Promise<{ data: Uint8Array; mimeType: string }> {
        captured.ttsEncoded.push(args);
        return { data: new Uint8Array([0xff, 0xf3]), mimeType: "audio/mpeg" };
      }
    }) as never;

  beforeEach(() => {
    vi.clearAllMocks();
    ws = new MockWebSocket();
    captured.textToImages.length = 0;
    captured.imageToImages.length = 0;
    captured.inpaintImages.length = 0;
    captured.ttsEncoded.length = 0;
  });

  afterEach(() => {
    ws.queue.length = 0;
  });

  it("image: forwards width, height, aspect ratio, resolution and variations", async () => {
    const runner = await makeRunner(ws, makeProvider);
    const out = await runOne(ws, runner, {
      command: "generate_media",
      request_id: "p-1",
      data: {
        mode: "image",
        provider: "fake",
        model: "m",
        prompt: "a cat",
        width: 1024,
        height: 640,
        aspect_ratio: "16:9",
        resolution: "2K",
        variations: 3
      }
    });
    expect(out.error).toBeUndefined();
    const call = captured.textToImages[0];
    expect(call.params.width).toBe(1024);
    expect(call.params.height).toBe(640);
    expect(call.params.aspectRatio).toBe("16:9");
    expect(call.params.resolution).toBe("2K");
    expect(call.params.prompt).toBe("a cat");
    expect(call.variations).toBe(3);
    await runner.disconnect();
  });

  it("image_edit: forwards source, target size, strength, steps and variations", async () => {
    configureAssets(["src-p2"]);
    const runner = await makeRunner(ws, makeProvider);
    const out = await runOne(ws, runner, {
      command: "generate_media",
      request_id: "p-2",
      data: {
        mode: "image_edit",
        provider: "fake",
        model: "m",
        prompt: "restyle",
        source_asset_id: "src-p2",
        width: 800,
        height: 600,
        strength: 0.8,
        num_inference_steps: 30,
        variations: 2
      }
    });
    expect(out.error).toBeUndefined();
    const call = captured.imageToImages[0];
    expect(call.images).toEqual([REF_BYTES["src-p2"]]);
    expect(call.params.prompt).toBe("restyle");
    expect(call.params.targetWidth).toBe(800);
    expect(call.params.targetHeight).toBe(600);
    expect(call.params.strength).toBe(0.8);
    expect(call.params.numInferenceSteps).toBe(30);
    expect(call.variations).toBe(2);
    await runner.disconnect();
  });

  it("inpaint: forwards source and mask bytes plus strength and steps", async () => {
    configureAssets(["src-p3", "mask-p3"]);
    const runner = await makeRunner(ws, makeProvider);
    const out = await runOne(ws, runner, {
      command: "generate_media",
      request_id: "p-3",
      data: {
        mode: "inpaint",
        provider: "fake",
        model: "m",
        prompt: "fill the sky",
        source_asset_id: "src-p3",
        mask_asset_id: "mask-p3",
        width: 512,
        height: 512,
        strength: 0.9,
        num_inference_steps: 20
      }
    });
    expect(out.error).toBeUndefined();
    const call = captured.inpaintImages[0];
    expect(call.images).toEqual([REF_BYTES["src-p3"]]);
    expect((call.params as { mask?: Uint8Array }).mask).toEqual(
      REF_BYTES["mask-p3"]
    );
    expect(call.params.prompt).toBe("fill the sky");
    expect(call.params.strength).toBe(0.9);
    expect(call.params.numInferenceSteps).toBe(20);
    await runner.disconnect();
  });

  it("image: derives pixel size from resolution + aspect ratio when none sent", async () => {
    const runner = await makeRunner(ws, makeProvider);
    const out = await runOne(ws, runner, {
      command: "generate_media",
      request_id: "p-5",
      data: {
        mode: "image",
        provider: "fake",
        model: "m",
        prompt: "wide scene",
        aspect_ratio: "16:9",
        resolution: "1K"
      }
    });
    expect(out.error).toBeUndefined();
    // 1K short edge; 16:9 scales the long edge — the node layer's arithmetic.
    expect(captured.textToImages[0].params.width).toBe(1820);
    expect(captured.textToImages[0].params.height).toBe(1024);
    await runner.disconnect();
  });

  it("image_edit: derives target size from resolution + aspect ratio", async () => {
    configureAssets(["src-p6"]);
    const runner = await makeRunner(ws, makeProvider);
    const out = await runOne(ws, runner, {
      command: "generate_media",
      request_id: "p-6",
      data: {
        mode: "image_edit",
        provider: "fake",
        model: "m",
        prompt: "widen",
        source_asset_id: "src-p6",
        aspect_ratio: "9:16",
        resolution: "2K"
      }
    });
    expect(out.error).toBeUndefined();
    // Portrait: the tier sets the short edge (width), ratio scales the other.
    expect(captured.imageToImages[0].params.targetWidth).toBe(2048);
    expect(captured.imageToImages[0].params.targetHeight).toBe(3641);
    await runner.disconnect();
  });

  it("audio: forwards voice, speed and audio format", async () => {
    const runner = await makeRunner(ws, makeProvider);
    const out = await runOne(ws, runner, {
      command: "generate_media",
      request_id: "p-4",
      data: {
        mode: "audio",
        provider: "fake",
        model: "tts-1",
        prompt: "We are closed.",
        voice: "alloy",
        speed: 1.2,
        audio_format: "mp3"
      }
    });
    expect(out.error).toBeUndefined();
    expect(captured.ttsEncoded[0]).toEqual({
      text: "We are closed.",
      model: "tts-1",
      voice: "alloy",
      speed: 1.2,
      audioFormat: "mp3"
    });
    await runner.disconnect();
  });
});
