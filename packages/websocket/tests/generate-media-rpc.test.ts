/**
 * Integration test for the `generate_media` RPC on the unified WebSocket.
 *
 * Regression guard: the sketch editor's direct text-to-image path must forward
 * the user-picked aspect ratio (and named resolution) to the provider. FAL's
 * image endpoints shape output via a size enum and ignore a raw {width,height}
 * dict, so without the aspect ratio the request falls back to a square default
 * — the "aspect ratio not honored" bug. This asserts the values reach
 * `textToImages` in the provider params.
 */
