import { nativeGameScriptCommandJsonSchema, nativeGame2dScriptCommandJsonSchema, nativeGameScriptCamera, exportNativeSchema } from "./native-game.js";
import type { z } from "zod";

type Schema = z.core.JSONSchema.JSONSchema;

function declaration(schema: Schema | boolean): string {
  if (schema === true) { return "unknown"; }
  if (schema === false) { return "never"; }
  if (schema.$ref) { return "NativeGameJson"; }
  if (schema.const !== undefined) { return JSON.stringify(schema.const); }
  if (schema.enum) { return schema.enum.map((value) => JSON.stringify(value)).join(" | "); }
  const alternatives = schema.oneOf ?? schema.anyOf;
  if (alternatives) { return alternatives.map(declaration).join(" | "); }
  if (schema.type === "null") { return "null"; }
  if (schema.type === "string" || schema.type === "boolean") { return schema.type; }
  if (schema.type === "number" || schema.type === "integer") { return "number"; }
  if (schema.type === "array") {
    if (schema.prefixItems) { return `readonly [${schema.prefixItems.map(declaration).join(", ")}]`; }
    if (!schema.items || Array.isArray(schema.items)) { throw new Error("Native script array requires typed items"); }
    return `ReadonlyArray<${declaration(schema.items)}>`;
  }
  if (schema.type === "object") {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(([name, property]) =>
      `readonly ${JSON.stringify(name)}${required.has(name) && (property === true || property === false || property.default === undefined) ? "" : "?"}: ${declaration(property)}`);
    if (schema.additionalProperties && schema.additionalProperties !== true) {
      fields.push(`readonly [key: string]: ${declaration(schema.additionalProperties)}`);
    }
    return `{ ${fields.join("; ")} }`;
  }
  throw new Error("Unsupported native script declaration schema");
}

/** Guest declarations derive command fields from the admitted engine contract. */
export function nativeGameScriptDeclarations(dimension: "2d" | "3d" = "3d"): string {
  return [
    "// Generated by generate-native-game-schema.ts. Do not edit.",
    "type NativeGameJson = null | boolean | number | string | Array<NativeGameJson> | { [key: string]: NativeGameJson };",
    `type NativeGameCommand = ${declaration(dimension === "2d" ? nativeGame2dScriptCommandJsonSchema() : nativeGameScriptCommandJsonSchema())};`,
    `type NativeGameCamera = ${dimension === "3d" ? declaration(exportNativeSchema(nativeGameScriptCamera)) : "Readonly<Record<string, never>>"};`,
    "interface NativeGameScriptResult { readonly state?: NativeGameJson; readonly commands?: ReadonlyArray<NativeGameCommand> }",
    "interface NativeGameScriptWorld { get(id: string): NativeGameJson | null; query(query: Omit<Extract<NativeGameCommand, { kind: 'query' }>, 'kind'> & { kind?: 'query' }): void }",
    "interface NativeGameScriptInput { readonly camera: NativeGameCamera; readonly tick: number; readonly entityId: string; readonly behaviorId: string; state: NativeGameJson; readonly props: Readonly<Record<string, NativeGameJson>>; readonly world: NativeGameScriptWorld; readonly input: Readonly<Record<string, NativeGameJson>> & { readonly loaded?: ReadonlyArray<{ readonly scope: 'progress' | 'settings'; readonly slot: string; readonly data: { readonly [key: string]: NativeGameJson } | null }> }; readonly events: ReadonlyArray<NativeGameJson>; readonly queryResults: NativeGameJson; random(): number; command(value: NativeGameCommand): void; log(...values: ReadonlyArray<unknown>): void }",
    "type NativeGameHook = (input: NativeGameScriptInput) => NativeGameScriptResult | void;",
    "declare function command(value: NativeGameCommand): void;",
    "declare function after(ticks: number, name: string): void;",
    "declare function every(ticks: number, name: string): void;",
    "declare function cancelTimer(name: string): void;",
    "declare function log(...values: ReadonlyArray<unknown>): void;",
    "interface NativeGameHooks { readonly onStart?: NativeGameHook; readonly onSceneEnter?: NativeGameHook; readonly onTriggerEnter?: NativeGameHook; readonly onTriggerExit?: NativeGameHook; readonly onContact?: NativeGameHook; readonly onEvent?: NativeGameHook; readonly onFixedUpdate?: NativeGameHook; readonly onUpdate?: NativeGameHook; readonly onDestroy?: NativeGameHook }",
    ""
  ].join("\n");
}
