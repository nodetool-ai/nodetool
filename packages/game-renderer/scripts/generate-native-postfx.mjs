import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createCanvas, loadImage } from '@napi-rs/canvas';
import { SMAAEdgesShader, SMAAWeightsShader, SMAABlendShader } from 'three/addons/shaders/SMAAShader.js';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const source = await readFile(resolve(root, 'node_modules/three/examples/jsm/postprocessing/SMAAPass.js'), 'utf8');
const check = process.argv.includes('--check');
async function output(path, bytes) {
  const target = resolve(root, path);
  if (check) { if (!Buffer.from(bytes).equals(await readFile(target))) { throw new Error(`Native postFX generation drift: ${path}`); } }
  else { await mkdir(resolve(target, '..'), { recursive: true }); await writeFile(target, bytes); }
}
const lookups = {};
for (const [key, method] of [['area', '_getAreaTexture'], ['search', '_getSearchTexture']]) {
  const body = source.slice(source.indexOf(`\n\t${method}()`));
  const match = /return 'data:image\/png;base64,([^']+)';/.exec(body);
  if (!match) { throw new Error(`Pinned Three SMAA ${key} lookup missing`); }
  const png = Buffer.from(match[1], 'base64');
  const image = await loadImage(png), canvas = createCanvas(image.width, image.height), ctx = canvas.getContext('2d');
  ctx.drawImage(image, 0, 0);
  const rgba = ctx.getImageData(0, 0, image.width, image.height).data;
  lookups[`native-smaa-${key}.png`] = { pngDigest: sha(png), rgbaDigest: sha(rgba), width: image.width, height: image.height, base64: png.toString('base64') };
  await output(`native/game/assets/native-smaa-${key}.png`, png);
}
const manifest = Object.fromEntries(Object.entries(lookups).map(([name, { base64, ...entry }]) => [name, entry]));
await output('native/game/assets/native-smaa.json', JSON.stringify({ source: 'three@0.185.1/examples/jsm/postprocessing/SMAAPass.js', lookups: manifest }, null, 2) + '\n');
await output('packages/game-renderer/src/native-cpp/3d-builtins.ts', `// Generated by scripts/generate-native-postfx.mjs from pinned Three SMAAPass.\n// Three MIT and SMAA notices: native/game/licenses/{three,SMAA}-LICENSE.\nexport const NATIVE_POST_BUILTINS = ${JSON.stringify(lookups, null, 2)} as const;\nexport type NativeBuiltinName = keyof typeof NATIVE_POST_BUILTINS;\nexport async function resolveNativeBuiltin(name: NativeBuiltinName): Promise<Uint8Array> {\n  const entry = NATIVE_POST_BUILTINS[name];\n  if (!entry) { throw new Error('Unknown native renderer builtin'); }\n  const bytes = Uint8Array.from(atob(entry.base64), character => character.charCodeAt(0));\n  const hash = Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256', bytes)), value => value.toString(16).padStart(2, '0')).join('');\n  if (hash !== entry.pngDigest) { throw new Error('Native SMAA builtin integrity mismatch'); }\n  return bytes;\n}\n`);
const header = '// Adapted from three@0.185.1 SMAAShader.js (SMAA 1x Medium).\n// Three MIT and upstream SMAA notices in native/game/licenses.\n#version 440\n';
const block = 'layout(std140,binding=0) uniform Params { mat4 clipCorrection; vec4 metrics; vec4 p0; vec4 p1; vec4 p2; vec4 weights[22]; };\n#define resolution metrics.xy\n';
for (const [name, shader] of [['edges', SMAAEdgesShader], ['weights', SMAAWeightsShader], ['blend', SMAABlendShader]]) {
  for (const stage of ['vert', 'frag']) {
    let code = stage === 'vert' ? shader.vertexShader : shader.fragmentShader;
    code = code.replace(/uniform vec2 resolution\s*;/g, '');
    let location = 0;
    code = code.replace(/varying\s+(vec\d)\s+(\w+)\s*(\[\s*\d+\s*\])?\s*;/g, (_, type, field, array) => {
      const item = `layout(location=${location}) ${stage === 'vert' ? 'out' : 'in'} ${type} ${field}${array ?? ''};`;
      location += array ? Number(array.replace(/\D/g, '')) : 1; return item;
    });
    let declarations;
    if (stage === 'vert') {
      declarations = 'layout(location=0) in vec3 position; layout(location=1) in vec2 uv;\n';
      code = code.replace('projectionMatrix * modelViewMatrix * vec4( position, 1.0 )', 'clipCorrection * vec4( position, 1.0 )');
    } else {
      declarations = 'layout(location=0) out vec4 outColor;\n';
      let binding = 1;
      code = code.replace(/uniform sampler2D (\w+)\s*;/g, (_, field) => `layout(binding=${binding++}) uniform sampler2D ${field};`);
      code = code.replace(/texture2D\(\s*(areaTex|searchTex)\s*,/g, 'texture($1,');
      code = code.replaceAll('texture2D(', 'sampleRT(').replaceAll('gl_FragColor', 'outColor');
      declarations += 'vec4 sampleRT(sampler2D tex,vec2 coord){return texture(tex,vec2(coord.x,metrics.z>0.5?coord.y:1.0-coord.y));}\nvec4 sampleRT(sampler2D tex,vec2 coord,float bias){return texture(tex,vec2(coord.x,metrics.z>0.5?coord.y:1.0-coord.y),bias);}\n';
    }
    const defines = Object.entries(shader.defines ?? {}).map(([key, value]) => `#define ${key} ${value}\n`).join('');
    await output(`native/game/src/render/shaders/postfx_smaa_${name}.${stage}`, header + block + defines + declarations + code);
  }
}
console.log(`Verified ${Object.keys(lookups).length} SMAA lookup resources and six native shader stages`);
