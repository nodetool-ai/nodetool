#!/usr/bin/env node
/**
 * Bundles the MCP Apps renderer (`mcp-app/`) into one self-contained HTML page
 * and embeds it in `src/mcp-app-renderer.generated.ts`. The NodeTool MCP
 * server serves that string as its `ui://` mini app resource, so the page can
 * load nothing at runtime: a host's sandbox allows inline script and style
 * only.
 *
 * The renderer reuses the exported app's widgets and runtime hook from
 * `template/src/`. The one module it replaces is `runtime/server.ts`, which
 * fetches a local Node server there and calls MCP tools through the host here.
 *
 *   node scripts/build-mcp-app.mjs          write the generated module
 *   node scripts/build-mcp-app.mjs --check  fail when it is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "src", "mcp-app-renderer.generated.ts");
const templateServer = resolve(root, "template", "src", "runtime", "server");
const mcpServer = resolve(root, "mcp-app", "src", "server.ts");

/** Point the template's `runtime/server` imports at the MCP transport. */
const swapServerModule = {
  name: "swap-server-module",
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /(^|\/)server$/ }, (args) => {
      const target = resolve(args.resolveDir, args.path);
      return target === templateServer ? { path: mcpServer } : undefined;
    });
  }
};

/** `</script` inside the bundle would end the inline script element early. */
const inlineScript = (code) => code.replace(/<\/script/gi, "<\\/script");
const inlineStyle = (code) => code.replace(/<\/style/gi, "<\\/style");

export async function renderMcpAppModule() {
  const result = await build({
    entryPoints: [join(root, "mcp-app", "src", "main.tsx")],
    bundle: true,
    write: false,
    outdir: "out",
    format: "iife",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
    charset: "utf8",
    jsx: "automatic",
    conditions: ["nodetool-dev"],
    define: { "process.env.NODE_ENV": '"production"' },
    plugins: [swapServerModule],
    logLevel: "silent"
  });
  const js = result.outputFiles.find((file) => file.path.endsWith(".js"))?.text ?? "";
  const css = result.outputFiles.find((file) => file.path.endsWith(".css"))?.text ?? "";
  if (!js) throw new Error("esbuild produced no script for the MCP app renderer");
  const html = [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8" />',
    '<meta name="viewport" content="width=device-width, initial-scale=1" />',
    "<title>NodeTool app</title>",
    `<style>${inlineStyle(css.trim())}</style>`,
    "</head>",
    "<body>",
    '<div id="root"></div>',
    `<script>${inlineScript(js.trim())}</script>`,
    "</body>",
    "</html>",
    ""
  ].join("\n");
  return [
    "// Generated by scripts/build-mcp-app.mjs from mcp-app/ and template/src/. Do not edit.",
    "",
    `export const MCP_APP_RENDERER_HTML: string = ${JSON.stringify(html)};`,
    ""
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await renderMcpAppModule();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outFile, "utf8");
    } catch {
      // Missing counts as stale.
    }
    if (current !== next) {
      console.error("src/mcp-app-renderer.generated.ts is stale. Run: npm run build-mcp-app --workspace=packages/app-export");
      process.exit(1);
    }
    console.log("src/mcp-app-renderer.generated.ts is current");
  } else {
    writeFileSync(outFile, next);
    console.log(`Wrote src/mcp-app-renderer.generated.ts (${Math.round(next.length / 1024)} KB)`);
  }
}
