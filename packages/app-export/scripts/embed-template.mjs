#!/usr/bin/env node
/**
 * Embeds `template/` into `src/template-files.generated.ts`, so the exporter
 * carries the project template as data and never reads files at runtime
 * (the packaged desktop backend flattens package paths).
 *
 *   node scripts/embed-template.mjs          write the generated module
 *   node scripts/embed-template.mjs --check  fail when it is out of date
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const templateDir = join(root, "template");
const outFile = join(root, "src", "template-files.generated.ts");

/** The placeholder bundle only exists so the template typechecks. */
const SKIP = new Set(["app.bundle.json"]);

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

export function renderTemplateModule() {
  const files = walk(templateDir)
    .map((path) => relative(templateDir, path).split(sep).join("/"))
    .filter((path) => !SKIP.has(path))
    .sort();
  const entries = files.map(
    (path) => `  [${JSON.stringify(path)}, ${JSON.stringify(readFileSync(join(templateDir, path), "utf8"))}]`
  );
  return [
    "// Generated by scripts/embed-template.mjs from template/. Do not edit.",
    "",
    "export const TEMPLATE_FILES: ReadonlyMap<string, string> = new Map([",
    entries.join(",\n"),
    "]);",
    ""
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = renderTemplateModule();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outFile, "utf8");
    } catch {
      // Missing counts as stale.
    }
    if (current !== next) {
      console.error("src/template-files.generated.ts is stale. Run: npm run embed-template --workspace=packages/app-export");
      process.exit(1);
    }
    console.log("src/template-files.generated.ts is current");
  } else {
    writeFileSync(outFile, next);
    console.log(`wrote ${relative(process.cwd(), outFile)}`);
  }
}
