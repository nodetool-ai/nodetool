import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { Asset, initTestDb, ModelObserver } from "@nodetool-ai/models";
import { InMemoryStorageAdapter } from "@nodetool-ai/storage";
import { createAssetModelInterface, updateAssetBytesModelInterface } from "../src/index.js";
import { getAssetFileName, getAssetStorageKey } from "../src/asset-paths.js";
import { getAssetAdapter } from "../src/storage.js";

vi.mock("../src/storage.js", () => ({ getAssetAdapter: vi.fn() }));
let storage: InMemoryStorageAdapter;
beforeEach(() => {
  initTestDb();
  storage = new InMemoryStorageAdapter();
  vi.mocked(getAssetAdapter).mockReturnValue(storage);
});
afterEach(() => { ModelObserver.clear(); });

it("persists generated bytes and ownership through the canonical service", async () => {
  const bytes = new Uint8Array([0, 255, 1]);
  const asset = await createAssetModelInterface({ userId: "owner", name: "binary", contentType: "application/octet-stream", content: bytes, metadata: { generation_id: "generated" } });
  expect(asset.parent_id).toBe("owner");
  expect(asset.metadata).toEqual({ generation_id: "generated" });
  expect((await Asset.find("owner", asset.id))?.size).toBe(3);
  const key = getAssetStorageKey("owner", asset.id, asset.content_type);
  expect(await storage.retrieve(storage.uriForKey(key))).toEqual(bytes);
  expect(getAssetFileName(asset.id, asset.content_type)).toContain(asset.id);
  expect(await updateAssetBytesModelInterface({ userId: "other", assetId: asset.id, content: new Uint8Array([7]) })).toBeNull();
  expect(await updateAssetBytesModelInterface({ userId: "owner", assetId: asset.id, content: new Uint8Array([7]) })).toMatchObject({ id: asset.id });
  expect(await storage.retrieve(storage.uriForKey(key))).toEqual(new Uint8Array([7]));
});
